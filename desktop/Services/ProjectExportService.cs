using System.IO;
using System.Text;
using CodeVision.Desktop.Models;

namespace CodeVision.Desktop.Services;

public sealed class ProjectExportService
{
    private readonly LoggingService _logger;

    public ProjectExportService(LoggingService logger)
    {
        _logger = logger;
    }

    public async Task<string> ExportReconstructedProjectAsync(
        string targetDirectory,
        string projectName,
        IEnumerable<ExtractedCodeSnippet> snippets,
        CancellationToken cancellationToken = default)
    {
        if (string.IsNullOrWhiteSpace(targetDirectory))
            throw new ArgumentException("مسار مجلد التصدير فارغ.", nameof(targetDirectory));

        var cleanProjectName = string.Join("_", projectName.Split(Path.GetInvalidFileNameChars()));
        if (string.IsNullOrWhiteSpace(cleanProjectName)) cleanProjectName = "ReconstructedApp";

        var projectFolder = Path.Combine(targetDirectory, cleanProjectName);
        Directory.CreateDirectory(projectFolder);

        _logger.Info($"Exporting reconstructed project to: {projectFolder}");

        var reportSb = new StringBuilder();
        reportSb.AppendLine($"# تقرير إعادة بناء وتصدير المشروع · CodeVision Studio Cyber Edition");
        reportSb.AppendLine($"**اسم المشروع:** {cleanProjectName}");
        reportSb.AppendLine($"**تاريخ التصدير:** {DateTime.Now:yyyy-MM-dd HH:mm:ss}");
        reportSb.AppendLine($"**محرك إعادة البناء:** SequenceMatcher + Unity Categorizer v5.0");
        reportSb.AppendLine();
        reportSb.AppendLine("## قائمة الملفات المستعادة والأدلة البرمجية:");
        reportSb.AppendLine();

        bool hasUnity = false;
        bool hasCSharp = false;
        bool hasFlutter = false;
        bool hasPython = false;
        bool hasTypeScript = false;

        // Write source files
        foreach (var snippet in snippets)
        {
            cancellationToken.ThrowIfCancellationRequested();

            var relativePath = string.IsNullOrWhiteSpace(snippet.TargetFilePath) ? "Program.cs" : snippet.TargetFilePath;
            
            // Clean relative path
            relativePath = relativePath.Replace('/', Path.DirectorySeparatorChar).Replace('\\', Path.DirectorySeparatorChar);
            var fullPath = Path.Combine(projectFolder, relativePath);

            var dir = Path.GetDirectoryName(fullPath);
            if (!string.IsNullOrEmpty(dir)) Directory.CreateDirectory(dir);

            await File.WriteAllTextAsync(fullPath, snippet.CodeContent, Encoding.UTF8, cancellationToken);

            var content = snippet.CodeContent;
            if (content.Contains("MonoBehaviour") || content.Contains("UnityEngine"))
                hasUnity = true;
            if (snippet.Language.Contains("C#") || relativePath.EndsWith(".cs"))
                hasCSharp = true;
            if (snippet.Language.Contains("Dart") || relativePath.EndsWith(".dart") || content.Contains("package:flutter") || content.Contains("Widget build") || content.Contains("StatelessWidget"))
                hasFlutter = true;
            if (snippet.Language.Contains("Python") || relativePath.EndsWith(".py") || content.Contains("def ") && content.Contains("import "))
                hasPython = true;
            if (snippet.Language.Contains("TypeScript") || snippet.Language.Contains("JavaScript") || relativePath.EndsWith(".ts") || relativePath.EndsWith(".js"))
                hasTypeScript = true;

            reportSb.AppendLine($"- **الملف:** `{relativePath}`");
            reportSb.AppendLine($"  - اللغة: {snippet.Language}");
            reportSb.AppendLine($"  - توقيت الفيديو: {snippet.TimestampFormatted}");
            reportSb.AppendLine($"  - درجة الثقة: {snippet.ConfidencePercent}");
            if (snippet.Confidence < 0.85)
            {
                reportSb.AppendLine($"  - ⚠️ *تنبيه:* مقطع ثقته منخفضة نسبياً، يرجى مراجعته يدوياً.");
            }
            reportSb.AppendLine();
        }

        // 1. Generate Flutter project files if Flutter/Dart snippets present
        if (hasFlutter)
        {
            var pubspecPath = Path.Combine(projectFolder, "pubspec.yaml");
            if (!File.Exists(pubspecPath))
            {
                var pubspecYaml = $@"name: {cleanProjectName.ToLower()}
description: A reconstructed Flutter project generated by CodeVision AI Studio.
publish_to: 'none'
version: 1.0.0+1

environment:
  sdk: '>=3.0.0 <4.0.0'

dependencies:
  flutter:
    sdk: flutter
  cupertino_icons: ^1.0.6

dev_dependencies:
  flutter_test:
    sdk: flutter
  flutter_lints: ^3.0.0

flutter:
  uses-material-design: true
";
                await File.WriteAllTextAsync(pubspecPath, pubspecYaml, Encoding.UTF8, cancellationToken);
            }

            var libDir = Path.Combine(projectFolder, "lib");
            Directory.CreateDirectory(libDir);
            var mainDartPath = Path.Combine(libDir, "main.dart");
            if (!File.Exists(mainDartPath))
            {
                var mainDart = $@"import 'package:flutter/material.dart';

void main() {{
  runApp(const ReconstructedApp());
}}

class ReconstructedApp extends StatelessWidget {{
  const ReconstructedApp({{super.key}});

  @override
  Widget build(BuildContext context) {{
    return MaterialApp(
      title: '{cleanProjectName}',
      theme: ThemeData(
        colorScheme: ColorScheme.fromSeed(seedColor: Colors.deepPurple),
        useMaterial3: true,
      ),
      home: const Scaffold(
        body: Center(
          child: Text('Reconstructed by CodeVision AI Studio'),
        ),
      ),
    );
  }}
}}
";
                await File.WriteAllTextAsync(mainDartPath, mainDart, Encoding.UTF8, cancellationToken);
            }
        }

        // 2. Generate Python project files if Python snippets present
        if (hasPython)
        {
            var reqPath = Path.Combine(projectFolder, "requirements.txt");
            if (!File.Exists(reqPath))
            {
                await File.WriteAllTextAsync(reqPath, "# CodeVision Reconstructed Python Project\n", Encoding.UTF8, cancellationToken);
            }
            var pyprojPath = Path.Combine(projectFolder, "pyproject.toml");
            if (!File.Exists(pyprojPath))
            {
                var pyproj = $@"[project]
name = ""{cleanProjectName.ToLower()}""
version = ""0.1.0""
description = ""Reconstructed Python Project by CodeVision AI Studio""
readme = ""README.md""
requires-python = "">=3.10""
dependencies = []
";
                await File.WriteAllTextAsync(pyprojPath, pyproj, Encoding.UTF8, cancellationToken);
            }
        }

        // 3. Generate Node / TypeScript project files if Web snippets present
        if (hasTypeScript)
        {
            var pkgJsonPath = Path.Combine(projectFolder, "package.json");
            if (!File.Exists(pkgJsonPath))
            {
                var pkgJson = $@"[
  ""name"": ""{cleanProjectName.ToLower()}"",
  ""version"": ""1.0.0"",
  ""description"": ""Reconstructed Project by CodeVision AI Studio"",
  ""main"": ""index.js"",
  ""scripts"": {{
    ""build"": ""tsc"",
    ""start"": ""node dist/index.js""
  }},
  ""devDependencies"": {{
    ""typescript"": ""^5.0.0""
  }}
]";
                pkgJson = pkgJson.Replace('[', '{').Replace(']', '}');
                await File.WriteAllTextAsync(pkgJsonPath, pkgJson, Encoding.UTF8, cancellationToken);
            }
        }

        // 4. Generate C# project file if C# snippets present
        if (hasCSharp)
        {
            var csprojPath = Path.Combine(projectFolder, $"{cleanProjectName}.csproj");
            var csprojXml = $@"<Project Sdk=""Microsoft.NET.Sdk"">
  <PropertyGroup>
    <OutputType>Library</OutputType>
    <TargetFramework>net9.0</TargetFramework>
    <Nullable>enable</Nullable>
    <ImplicitUsings>enable</ImplicitUsings>
    <RootNamespace>{cleanProjectName}</RootNamespace>
    <LangVersion>latest</LangVersion>
  </PropertyGroup>
</Project>";
            await File.WriteAllTextAsync(csprojPath, csprojXml, Encoding.UTF8, cancellationToken);

            // Generate Visual Studio Solution .sln
            var slnGuid = Guid.NewGuid().ToString("B").ToUpper();
            var projGuid = Guid.NewGuid().ToString("B").ToUpper();
            var slnContent = $@"Microsoft Visual Studio Solution File, Format Version 12.00
# Visual Studio Version 17
VisualStudioVersion = 17.0.31903.59
MinimumVisualStudioVersion = 10.0.40219.1
Project(""{slnGuid}"") = ""{cleanProjectName}"", ""{cleanProjectName}.csproj"", ""{projGuid}""
EndProject
Global
	GlobalSection(SolutionConfigurationPlatforms) = preSolution
		Debug|Any CPU = Debug|Any CPU
		Release|Any CPU = Release|Any CPU
	EndGlobalSection
	GlobalSection(ProjectConfigurationPlatforms) = postSolution
		{projGuid}.Debug|Any CPU.ActiveCfg = Debug|Any CPU
		{projGuid}.Debug|Any CPU.Build.0 = Debug|Any CPU
		{projGuid}.Release|Any CPU.ActiveCfg = Release|Any CPU
		{projGuid}.Release|Any CPU.Build.0 = Release|Any CPU
	EndGlobalSection
EndGlobal
";
            var slnPath = Path.Combine(projectFolder, $"{cleanProjectName}.sln");
            await File.WriteAllTextAsync(slnPath, slnContent, Encoding.UTF8, cancellationToken);
        }

        // Determine target environment description
        var targetEnvs = new List<string>();
        if (hasFlutter) targetEnvs.Add("تطبيقات فلاتر الهجينة (Flutter / Dart Project)");
        if (hasUnity) targetEnvs.Add("محرك ألعاب Unity (Scripts & Components)");
        if (hasCSharp && !hasUnity) targetEnvs.Add(".NET 9 Standard / C# Library");
        if (hasPython) targetEnvs.Add("حزم بايثون الحديثة (Python 3.10+)");
        if (hasTypeScript) targetEnvs.Add("تطبيقات الويب و TypeScript");
        if (targetEnvs.Count == 0) targetEnvs.Add("شفرات ومكونات برمجية مستقلة");

        // Write verification report
        reportSb.AppendLine($"**البيئة المستهدفة:** {string.Join(" + ", targetEnvs)}");
        var reportPath = Path.Combine(projectFolder, "RECONSTRUCTION_REPORT.md");
        await File.WriteAllTextAsync(reportPath, reportSb.ToString(), Encoding.UTF8, cancellationToken);

        _logger.Info($"Project exported successfully with {snippets.Count()} files to {projectFolder}.");
        return projectFolder;
    }
}
